const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert');
const nodes=new Map();const get=id=>{if(!nodes.has(id))nodes.set(id,{value:'',checked:false});return nodes.get(id)};
const ctx={document:{getElementById:get},URL,TextEncoder,Uint8Array,DataView,Date,setTimeout,console};vm.createContext(ctx);
for(const file of process.argv[2]?[process.argv[2]]:['dist/contact-template.js','dist/generator.js','dist/xlsx.js','dist/app.js','dist/prompt.js'])vm.runInContext(fs.readFileSync(file,'utf8'),ctx);
assert(/id="published" checked/.test(fs.readFileSync('dist/index.html','utf8')));
get('published').checked=true;
const input={brand:'Test & Sample',email:'',website:'',refTitle:'Skincare essentials',refBody:'Hydration and skin barrier care with a dewy glow.',discount:'35',date:'',details:''};
ctx.input=input;
const prompt=vm.runInContext("buildMarketingPrompt(input,['size-chart','home-title'],['discount','shipping'],'Custom SEO facts','https://example.com/product')",ctx);
assert(prompt.includes('最高 35% OFF'));
assert(prompt.includes('Custom SEO facts'));
assert(prompt.includes('源网址（参考资料）：https://example.com/product'));
assert(prompt.includes('尺码表')&&prompt.includes('不得编造数值'));
assert(prompt.includes('style 属性')&&prompt.includes('Markdown 代码围栏')&&prompt.includes('不得包含 JavaScript'));
assert(prompt.includes('其他所选板块仍按各自要求生成'));
const sizeOnly=vm.runInContext("buildMarketingPrompt(input,['size-chart'],[])",ctx);
assert(sizeOnly.includes('整个回答必须是可直接粘贴的纯 HTML 片段'));
assert(sizeOnly.includes('不添加中文板块标注、推荐放置位置'));
assert(!prompt.includes('首页大屏广告提示词'));
assert(prompt.includes('着重体现：折扣、免运费'));
assert.throws(()=>vm.runInContext("buildMarketingPrompt(input,[],[])",ctx),/至少选择/);
assert.throws(()=>vm.runInContext("buildMarketingPrompt(input,['banner'],[],'','javascript:alert(1)')",ctx),/仅支持/);
const allPrompt=vm.runInContext("buildMarketingPrompt({...input,brand:'Another Brand',discount:'18'},promptOptions.map(x=>x[0]),[])",ctx);
assert(allPrompt.includes('Another Brand')&&allPrompt.includes('最高 18% OFF'));
assert(!allPrompt.includes('源网址（参考资料）'));
assert(!allPrompt.includes('着重体现：'));
assert(vm.runInContext('promptOptions.length',ctx)===12);
const result=vm.runInContext('generateLocal(input)',ctx);
assert.equal(result.pages.length,7);
const about=result.pages[0].body_html;
const count=about.replace(/<[^>]+>/g,' ').match(/\b[\w]+(?:['’-][\w]+)*\b/g).length;
assert(count>=3000,`About Us only has ${count} words`);
assert(result.pages.every(p=>p.body_html.length<=32767),'Excel cell limit exceeded');
assert(result.pages.every(p=>!p.body_html.includes('mailto:')),'Blank email must not create empty mailto link');
assert(result.pages.every(p=>!p.body_html.includes('Last updated:')),'Blank date must not add a date');
assert(result.marketing.announcements[1].includes('35%'));
assert(result.marketing.announcements[1].startsWith('A little something for your everyday'));
assert(!/free shipping|free worldwide|<table/i.test(result.pages.find(p=>p.handle==='shipping-policy').body_html));
assert(!/cookie|GDPR|CCPA|【/i.test(result.pages.find(p=>p.handle==='privacy-policy').body_html));
const personalized=vm.runInContext("generateLocal({...input,email:'help@example.com',date:'2026-12-20',refTitle:'Clothing',refBody:'Soft comfortable apparel',discount:'20'})",ctx);
assert(personalized.pages[1].body_html.includes('mailto:help@example.com'));
assert(personalized.pages[1].body_html.includes('2026-12-20'));
assert(personalized.pages[0].body_html.includes('clothing and everyday style essentials'));
assert(personalized.marketing.announcements[1].includes('holiday'));
const escaped=vm.runInContext("generateLocal({...input,brand:'<script>alert(1)</script>'})",ctx);
assert(!escaped.pages[0].body_html.includes('<script>'));
assert.deepEqual(escaped.pages,result.pages,'Changing the brand must not change page templates');
const unbranded=vm.runInContext("generateLocal({...input,brand:''})",ctx);
assert.deepEqual(unbranded.pages,result.pages,'Pages must also work without a brand');
assert(result.pages.every(p=>!p.body_html.includes('Test &amp; Sample')&&!p.body_html.includes('{brand}')));
assert(!JSON.stringify(unbranded.marketing).includes('undefined'));
assert(!unbranded.marketing.seo.some(p=>p.title.endsWith(' | ')));
ctx.result=result;
vm.runInContext("data=result;data.pages.push({handle:'contact-us',title:'Contact Us',body_html:CONTACT_HTML})",ctx);
assert(vm.runInContext('rows().slice(1).every(row=>row[8]===true)',ctx));
get('published').checked=false;
assert(vm.runInContext('rows().slice(1).every(row=>row[8]===false)',ctx));
get('published').checked=true;
const bytes=vm.runInContext('workbook(rows())',ctx);
const menus=vm.runInContext('menuRows()',ctx);
assert.equal(menus.length,9);
assert.equal(menus[0].length,18);
assert.deepEqual(Array.from(menus.slice(1,3),r=>r[12]),['contact-us','about-us']);
assert(menus.slice(3).every(r=>r[1]==='information'));
assert(menus.slice(1).every(r=>r[0]===''&&r[7]===''&&r[11]===''&&r[10]==='PAGE'&&r[14]==='/pages/'+r[12]));
assert.equal(menus.filter(r=>r[5]===true).length,2);
assert.deepEqual(Array.from(menus.slice(1),r=>r[17]),[1,2,1,2,3,4,5,6]);
fs.writeFileSync('export-check.xlsx',bytes);
console.log(`PASS: optional blank fields, category matching, seasonal/evergreen copy, discount substitution, escaping, 8-page export. About Us: ${count} words / ${about.length} characters.`);
